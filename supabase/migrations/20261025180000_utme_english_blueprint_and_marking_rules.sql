-- UTME Use of English: configurable paper blueprint and marking rules.
-- Reading-text pools are selected by a protected database setting. Only one novel
-- is used per paper; both pools can coexist for different exam cycles/templates.
-- This migration fails closed until the required Cloze Passage and selected novel
-- questions are imported and reviewed.

create table if not exists public.legacy_exam_marking_rules (
  id bigint generated by default as identity primary key,
  subject text not null,
  section text not null,
  category_pattern text not null,
  question_count integer not null check (question_count > 0),
  marks numeric(6,2) not null check (marks >= 0),
  passage_required boolean not null default false,
  sort_order integer not null default 100,
  enabled boolean not null default true,
  blueprint_key text not null default 'default',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (subject, section, category_pattern, blueprint_key)
);

alter table public.legacy_exam_marking_rules enable row level security;
revoke all on public.legacy_exam_marking_rules from anon, authenticated;

create table if not exists public.legacy_exam_blueprint_settings (
  setting_key text primary key,
  reading_text_key text not null check (reading_text_key in ('lekki_headmaster', 'life_changer')),
  updated_at timestamptz not null default now()
);
alter table public.legacy_exam_blueprint_settings enable row level security;
revoke all on public.legacy_exam_blueprint_settings from anon, authenticated;

-- Default to the current 2026 UTME prescribed text. Change this protected setting
-- when preparing a paper for a different exam cycle; never mix both novels in one paper.
