create or replace function public._legacy_exam_marks(p_question_id bigint)
returns numeric
language sql
stable
security definer
set search_path to 'public', 'pg_temp'
as $function$
  select coalesce(r.marks, q.marks)::numeric
  from public.questions q
  left join lateral (
    select rule.marks
    from public.legacy_exam_marking_rules rule
    where rule.enabled
      and lower(rule.subject) = lower(q.subject)
      and lower(rule.section) = lower(q.section)
      and q.category ilike rule.category_pattern
    order by rule.sort_order
    limit 1
  ) r on true
  where q.id = p_question_id;
$function$;

create or replace function public._build_paper(p_elective text)
returns bigint[]
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $function$
declare
  rule public.legacy_exam_marking_rules%rowtype;
  v_passage_id text;
  v_ids bigint[];
  v_english bigint[] := '{}';
  v_reading_text_key text;
begin
  if p_elective not in ('Biology', 'Mathematics') then
    raise exception 'Invalid elective subject: %', p_elective;
  end if;

  select reading_text_key into v_reading_text_key
  from public.legacy_exam_blueprint_settings
  where setting_key = 'utme_english';

  if v_reading_text_key is null then
    raise exception 'UTME English reading-text setting is missing.';
  end if;

  for rule in
    select *
    from public.legacy_exam_marking_rules
    where enabled and lower(subject) = 'english'
      and (blueprint_key = 'default' or blueprint_key = 'reading:' || v_reading_text_key)
    order by sort_order, id
  loop
    if rule.passage_required then
      select q.passage_id into v_passage_id
      from public.questions q
      where lower(q.subject) = lower(rule.subject)
        and lower(q.section) = lower(rule.section)
        and q.category ilike rule.category_pattern
        and q.is_active
        and nullif(trim(q.passage_id), '') is not null
      group by q.passage_id
      having count(*) >= rule.question_count
      order by random()
      limit 1;

      if v_passage_id is null then
        raise exception 'English paper unavailable: category "%" needs one passage with at least % active questions; none found.',
          rule.category_pattern, rule.question_count;
      end if;

      select coalesce(array_agg(picked.id), '{}') into v_ids
      from (
        select q.id
        from public.questions q
        where lower(q.subject) = lower(rule.subject)
          and lower(q.section) = lower(rule.section)
          and q.category ilike rule.category_pattern
          and q.is_active
          and q.passage_id = v_passage_id
        order by random()
        limit rule.question_count
      ) picked;
      v_passage_id := null;
    else
      select coalesce(array_agg(picked.id), '{}') into v_ids
      from (
        select q.id
        from public.questions q
        where lower(q.subject) = lower(rule.subject)
          and lower(q.section) = lower(rule.section)
          and q.category ilike rule.category_pattern
          and q.is_active
        order by random()
        limit rule.question_count
      ) picked;
    end if;

    if coalesce(cardinality(v_ids), 0) <> rule.question_count then
      raise exception 'English paper unavailable: category "%" needs % active questions; found %.',
        rule.category_pattern, rule.question_count, coalesce(cardinality(v_ids), 0);
    end if;

    v_english := v_english || v_ids;
  end loop;

  if coalesce(cardinality(v_english), 0) <> 60 then
    raise exception 'English paper blueprint misconfigured: expected 60 questions, configured rules selected %.',
      coalesce(cardinality(v_english), 0);
  end if;

  -- Do not silently fill gaps with questions from unrelated subjects.
  return v_english
      || public._pick_ids('Chemistry', 'objective', 40)
      || public._pick_ids('Physics', 'objective', 40)
      || public._pick_ids(p_elective, 'objective', 40);
end
$function$;

create or replace function public._paper_json(p_ids bigint[])
returns jsonb
language sql
stable
security definer
set search_path to 'public', 'pg_temp'
as $function$
  select coalesce(jsonb_agg(jsonb_build_object(
      'id', q.id, 'subject', q.subject, 'section', q.section, 'category', q.category,
      'passage_id', q.passage_id, 'passage_title', q.passage_title, 'passage_text', q.passage_text,
      'question', q.question,
      'question_image_url', q.question_image_url,
      'question_image_alt', q.question_image_alt,
      'option_a', q.option_a, 'option_a_image_url', q.option_a_image_url, 'option_a_image_alt', q.option_a_image_alt,
      'option_b', q.option_b, 'option_b_image_url', q.option_b_image_url, 'option_b_image_alt', q.option_b_image_alt,
      'option_c', q.option_c, 'option_c_image_url', q.option_c_image_url, 'option_c_image_alt', q.option_c_image_alt,
      'option_d', q.option_d, 'option_d_image_url', q.option_d_image_url, 'option_d_image_alt', q.option_d_image_alt,
      'marks', public._legacy_exam_marks(q.id)) order by array_position(p_ids, q.id)), '[]'::jsonb)
  from public.questions q
  where q.id = any (p_ids);
$function$;

create or replace function public._finalize_session(
  p_id uuid,
  p_answers jsonb,
  p_auto boolean,
  p_flagged jsonb
)
returns jsonb
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $function$
declare
  s public.exam_sessions%rowtype;
  v_late boolean;
  v_ans jsonb;
  v_status text;
  v_result_id uuid;
  v_score integer;
  v_total integer;
begin
  select * into s from public.exam_sessions where id = p_id for update;
  if not found then return public._err('invalid_session', 'Session not found.'); end if;
  if s.status = 'cancelled' then return public._err('cancelled', 'This attempt was cancelled.'); end if;
  if s.status <> 'started' then return public._result_payload(s.id, p_flagged); end if;

  v_late := now() > s.deadline_at + interval '60 seconds';
  v_status := case when v_late then 'expired' else 'submitted' end;
  v_ans := case when v_late or p_answers is null
    then s.draft_answers
    else public._clean_answers(p_answers, s.paper_ids)
  end;

  select sum(got)::int, sum(possible)::int into v_score, v_total
  from (
    select
      round(sum(case
        when (v_ans ->> q.id::text) = upper(trim(q.correct_answer))
          then public._legacy_exam_marks(q.id)
        else 0
      end)) as got,
      round(sum(public._legacy_exam_marks(q.id))) as possible
    from public.questions q
    where q.id = any (s.paper_ids)
    group by q.subject
  ) t;

  if v_total is null or v_total <= 0 then
    raise exception 'Cannot grade session %: empty paper', s.id;
  end if;

  insert into public.results (session_id, name, phone, subject, score, total)
  values (s.id::text, s.candidate_name, s.phone, coalesce(s.elective, s.subject), v_score, v_total)
  returning id into v_result_id;

  insert into public.answers
    (result_id, question_id, selected_answer, correct_answer, subject, question_text, is_correct, marks)
  select
    v_result_id,
    q.id,
    v_ans ->> q.id::text,
    upper(trim(q.correct_answer)),
    q.subject,
    q.question,
    coalesce((v_ans ->> q.id::text) = upper(trim(q.correct_answer)), false),
    public._legacy_exam_marks(q.id)
  from public.questions q
  where q.id = any (s.paper_ids);

  update public.exam_sessions
  set status = v_status,
      submitted_at = now(),
      auto_submitted = (coalesce(p_auto, false) or v_late),
      time_left_seconds = public._seconds_left(s.deadline_at),
      result_id = v_result_id,
      draft_answers = v_ans
  where id = s.id;

  return public._result_payload(s.id, p_flagged);
end
$function$;

